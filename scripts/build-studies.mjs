#!/usr/bin/env node
/** Regenerate the study libraries' shared CSS and standalone SVG files.
 *
 *  1. assets/color-systems/color-systems.css  ← assets/color-systems/*.json
 *  2. assets/{svg,motion,interactions,compositions}/study.css
 *       ← assets/runtime/study-frame.css + <library>/study.extra.css
 *         + any other <library>/*.extra.css (sorted) + color-systems.css
 *  3. assets/svg/<id>.svg for every diagram study that exports figure(theme):
 *       literal colors from the study's color system, so the file opens correctly
 *       in Figma, Illustrator, Keynote and PowerPoint (no CSS variables).
 *
 *  node scripts/build-studies.mjs [--check] [--css-only]
 *    --check     fail if any output would change
 *    --css-only  regenerate the CSS bundles only (skip the standalone SVGs)
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT } from './craft-core.mjs';
import { systemsCSS } from './color-systems.mjs';

const check = process.argv.includes('--check');
const cssOnly = process.argv.includes('--css-only');
const changed = [];
async function write(file, text) {
  const old = await fs.readFile(file, 'utf8').catch(() => null);
  if (old === text) return;
  changed.push(path.relative(ROOT, file));
  if (!check) await fs.writeFile(file, text);
}

const csDir = path.join(ROOT, 'assets/color-systems');
const systems = await Promise.all((await fs.readdir(csDir)).filter(f => f.endsWith('.json')).sort()
  .map(async f => ({ file: path.join(csDir, f), system: JSON.parse(await fs.readFile(path.join(csDir, f), 'utf8')) })));
const csCss = await systemsCSS(systems);
await write(path.join(csDir, 'color-systems.css'), csCss);

const frame = await fs.readFile(path.join(ROOT, 'assets/runtime/study-frame.css'), 'utf8');
for (const lib of ['svg', 'motion', 'interactions', 'compositions']) {
  const dir = path.join(ROOT, 'assets', lib);
  const extras = (await fs.readdir(dir)).filter(f => f.endsWith('.extra.css'))
    .sort((a, b) => (a === 'study.extra.css' ? -1 : b === 'study.extra.css' ? 1 : a.localeCompare(b)));
  let extra = '';
  for (const f of extras) extra += `/* ${lib}/${f} */\n${await fs.readFile(path.join(dir, f), 'utf8')}\n`;
  const bundle = `/* GENERATED by scripts/build-studies.mjs — edit assets/runtime/study-frame.css, assets/${lib}/*.extra.css or assets/color-systems/*.json instead. */\n${frame}\n${extra}\n${csCss}`;
  await write(path.join(ROOT, 'assets', lib, 'study.css'), bundle);
}

// Standalone SVGs with literal colors.
const byId = new Map(systems.map(s => [s.system.id, s.system]));
const { resources } = JSON.parse(await fs.readFile(path.join(ROOT, 'assets/catalog.json'), 'utf8'));
let svgs = 0;
for (const r of cssOnly ? [] : resources.filter(x => x.kind === 'diagrams')) {
  const mod = await import(pathToFileURL(path.join(ROOT, r.source)).href);
  if (typeof mod.figure !== 'function') continue;
  const cs = /\bcs-([a-z0-9-]+)/.exec(mod.default.className || '')?.[1];
  const system = cs ? byId.get(cs) : null;
  if (cs && !system) throw Error(`${r.id}: unknown color system cs-${cs}`);
  let svg = mod.figure(system || {});
  if (!/^<svg[^>]*\bxmlns=/.test(svg)) throw Error(`${r.id}: figure() must return a root <svg> with xmlns`);
  // Paint the paper behind the drawing so the standalone file matches the slide.
  const paper = system?.tokens?.paper || '#ffffff';
  const vb = /viewBox="([\d.\s-]+)"/.exec(svg)?.[1].trim().split(/\s+/).map(Number) || [0, 0, 1280, 720];
  svg = svg.replace(/^(<svg[^>]*>)(<title[^>]*>[\s\S]*?<\/title>(?:<desc[^>]*>[\s\S]*?<\/desc>)?)/, (m, open, meta) => `${open}${meta}<rect x="${vb[0]}" y="${vb[1]}" width="${vb[2]}" height="${vb[3]}" fill="${paper}"/>`);
  await write(path.join(ROOT, r.source.replace(/\.mjs$/, '.svg')), `<?xml version="1.0" encoding="UTF-8"?>\n${svg}\n`);
  svgs++;
}
console.log(JSON.stringify({ check, changed, standaloneSvgs: svgs }));
if (check && changed.length) { console.error('Out of date: ' + changed.join(', ') + '. Run node scripts/build-studies.mjs'); process.exitCode = 1; }
